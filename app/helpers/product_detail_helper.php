function findProductDetail(string $slug): ?array
{
    $slug = sanitizeSlug($slug);

    if ($slug === '') {
        return null;
    }

    $products = productDetailDefinitions();

    if (!isset($products[$slug])) {
        return null;
    }

    $product = $products[$slug];
    $product['slug'] = $slug;
    $product['imageUrl'] = assetUrl('images/' . $product['image']);
    $product['galleryUrls'] = array_map(
        static fn (string $image): string => assetUrl('images/' . $image),
        $product['gallery'] ?? [$product['image']]
    );

    return $product;
}

function productDetailUrl(string $slug): string
{
    return appUrl('/product-detail.php?product=' . rawurlencode(sanitizeSlug($slug)));
}

function productDetailSitemapPaths(): array
{
    return array_map(
        static fn (string $slug): string => '/product-detail.php?product=' . rawurlencode($slug),
        array_keys(productDetailDefinitions())
    );
}
